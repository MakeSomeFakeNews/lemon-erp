package com.lemon.erp.modules.bi.model;

/**
 * 周转分析的计算维度（issue #116）：按数量，或按 数量 × 价格 的金额计算周转率、周转天数。
 * 单个商品的价格不变时各维度结果相同，维度影响合计行（按金额加权）和没有价格的商品（按金额时不计算）
 */
public enum TurnoverBasis {
    /** 销售数量；金额列按库存均价（需要「查看成本金额」，没有时不返回金额） */
    QTY,
    /** 成本价：库存均价（实时移动加权平均），需要「查看成本金额」 */
    COST,
    /** 零售价（含税），需要售价查看权限 */
    RETAIL,
    /** 批发价（含税，所选价格列，只能选启用的列），需要售价查看权限 */
    WHOLESALE
}
